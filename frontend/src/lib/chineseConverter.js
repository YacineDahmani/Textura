// Create a reverse mapping for Traditional to Simplified
const T2S_MAP = {};
for (const [s, t] of Object.entries(S2T_MAP)) {
  // If a traditional character maps to multiple simplified characters,
  // we just keep the first one as character-level default
  if (!T2S_MAP[t]) {
    T2S_MAP[t] = s;
  }
}

/**
 * Converts Simplified Chinese text to Traditional Chinese text
 * @param {string} text 
 * @returns {string}
 */
export function convertToTraditional(text) {
  if (!text) return "";
  return text.split("").map(char => S2T_MAP[char] || char).join("");
}

/**
 * Converts Traditional Chinese text to Simplified Chinese text
 * @param {string} text 
 * @returns {string}
 */
export function convertToSimplified(text) {
  if (!text) return "";
  return text.split("").map(char => T2S_MAP[char] || char).join("");
}
